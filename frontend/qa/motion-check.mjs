import { chromium, expect } from '@playwright/test';
import { writeFileSync } from 'node:fs';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CAMPUSAI_CHROMIUM || 'C:/Users/ramuv/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe' });
const report = { checks: [], errors: [] };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  page.on('pageerror', e => report.errors.push(e.message));
  await page.goto(process.env.CAMPUSAI_PREVIEW || 'http://127.0.0.1:5180');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await expect(page.locator('.design-copy')).toHaveCSS('opacity', '1');
  await page.locator('.question-panel').scrollIntoViewIfNeeded();
  await expect(page.locator('.question-panel')).toHaveCSS('opacity', '1');
  const panel = await page.locator('.question-panel').boundingBox();
  await page.mouse.move(panel.x + panel.width - 25, panel.y + 30);
  await expect.poll(async () => page.locator('.glass-reflection').evaluate(element => new DOMMatrix(getComputedStyle(element).transform).m41)).toBeGreaterThan(20);
  await page.mouse.move(10, 500);
  await expect.poll(async () => page.locator('.glass-reflection').evaluate(element => Math.abs(new DOMMatrix(getComputedStyle(element).transform).m41))).toBeLessThan(1);
  report.checks.push({ name: 'Glass reflection follows the pointer and settles after leaving', passed: true });
  const assistant = page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Assistant', exact: true });
  const face = assistant.locator('.dock-face');
  const before = (await face.boundingBox()).width;
  await assistant.hover();
  await expect.poll(async () => (await face.boundingBox()).width).toBeGreaterThan(before + 6);
  await expect(assistant.locator('.dock-label')).toHaveCSS('opacity', '1');
  report.checks.push({ name: 'Dock magnifies on hover and reveals label', passed: true, before, enlarged: (await face.boundingBox()).width });
  await assistant.click({ button: 'right' });
  await expect(page.getByRole('menu')).toBeVisible();
  await expect(page.getByRole('menuitem', { name: 'Attendance and condonation' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).toHaveCount(0);
  await assistant.focus();
  await page.keyboard.press('ArrowUp');
  await expect(page.getByRole('menu')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(assistant).toBeFocused();
  report.checks.push({ name: 'Dock pointer and keyboard shortcut menus, Escape focus restoration', passed: true });
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Courses', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Courses', exact: true })).toHaveAttribute('data-hop', '');
  await expect(page).toHaveURL(/#explore$/);
  report.checks.push({ name: 'Dock click provides spring bounce feedback', passed: true });
  await page.getByRole('button', { name: 'CampusAI Home' }).click();
  await page.locator('#academic-tools').scrollIntoViewIfNeeded();
  await expect(page.locator('#academic-tools')).toHaveCSS('opacity', '1');
  await page.locator('#how-it-works').scrollIntoViewIfNeeded();
  await expect(page.locator('#how-it-works')).toHaveCSS('opacity', '1');
  report.checks.push({ name: 'Scroll reveals make lower sections visible', passed: true });
  await page.goto(process.env.CAMPUSAI_PREVIEW || 'http://127.0.0.1:5180');
  await expect(page.locator('.design-copy')).toHaveCSS('opacity', '1');
  await expect.poll(() => page.locator('.design-hero-art img').evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.mouse.move(10, 500);
  await page.screenshot({ path: 'qa/redesign/motion-light-desktop.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await page.mouse.move(10, 500);
  await page.screenshot({ path: 'qa/redesign/motion-dark-desktop.png', animations: 'disabled' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload();
  const reducedFace = page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('button', { name: 'Assistant', exact: true }).locator('.dock-face');
  const reducedSize = (await reducedFace.boundingBox()).width;
  await reducedFace.hover();
  await expect.poll(async () => (await reducedFace.boundingBox()).width).toBeCloseTo(reducedSize, 0);
  await expect(page.locator('.question-panel')).toHaveCSS('animation-name', 'none');
  await expect(page.locator('.landing-atmosphere')).toHaveCount(0);
  await expect(page.locator('#how-it-works')).toHaveCSS('opacity', '1');
  report.checks.push({ name: 'Reduced-motion preference removes entrances; decorative loops are absent', passed: true });
  await page.goto((process.env.CAMPUSAI_PREVIEW || 'http://127.0.0.1:5180') + '/#chat');
  let completeResponse;
  await page.route('**/api/v1/chat', async route => {
    await new Promise(resolve => { completeResponse = resolve; });
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ answer: 'Test answer with readable paragraphs.', session_id: 'ui-refinement' }) });
  });
  await page.getByRole('button', { name: 'Degree credits', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Preparing your answer');
  await expect(page.locator('.thinking-dots')).toBeVisible();
  completeResponse();
  await expect(page.getByText('Test answer with readable paragraphs.', { exact: true })).toBeVisible();
  await page.locator('.response-details summary').click();
  await expect(page.getByText('Source grounding was not confirmed.', { exact: true })).toBeVisible();
  await expect(page.getByText('Gazette Verified', { exact: true })).toHaveCount(0);
  report.checks.push({ name: 'Compact request status and honest service metadata', passed: true });
  await page.screenshot({ path: 'qa/redesign/chat-response-refined.png', animations: 'disabled' });
  const inputBounds = await page.getByLabel('Ask CampusAI', { exact: true }).boundingBox();
  expect(inputBounds.y + inputBounds.height).toBeLessThan(1000);
  const dockBounds = await page.locator('.dock').boundingBox();
  expect(inputBounds.y + inputBounds.height).toBeLessThan(dockBounds.y);
  report.checks.push({ name: 'Composer remains usable after the first answer', passed: true });
  const media = await page.context().newCDPSession(page);
  await media.send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-transparency', value: 'reduce' }, { name: 'prefers-reduced-motion', value: 'reduce' }] });
  for (const theme of ['dark', 'light']) {
    if (theme === 'light') await page.getByRole('button', { name: 'Switch to light mode' }).click();
    await expect.poll(() => page.evaluate(() => {
      const style = getComputedStyle(document.documentElement);
      return style.getPropertyValue('--glass').trim() === style.getPropertyValue('--surface').trim();
    })).toBe(true);
  }
  report.checks.push({ name: 'Reduced-transparency fallback is opaque in both themes', passed: true });
  expect(report.errors).toEqual([]);
} finally {
  writeFileSync('qa/redesign/motion-report.json', JSON.stringify(report, null, 2));
  await browser.close();
}
